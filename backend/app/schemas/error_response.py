from enum import Enum

from pydantic import BaseModel
from starlette import status


class ErrorCodeType(str, Enum):
    ENTITY_NOT_FOUND = "ENTITY_NOT_FOUND"
    INTEGRITY_ERROR = "INTEGRITY_ERROR"

    NOT_IMPLEMENTED = "NOT_IMPLEMENTED"

    INVALID_TOKEN = "INVALID_TOKEN"
    TOKEN_EXPIRED = "TOKEN_EXPIRED"
    INVALID_AUTH_DATA = "INVALID_AUTH_DATA"

    ACCOUNT_UPDATE_FORBIDDEN = "ACCOUNT_UPDATE_FORBIDDEN"
    ACCOUNT_DELETION_FORBIDDEN = "ACCOUNT_DELETION_FORBIDDEN"
    DELETED_ACCOUNT_TRANSACTION_FORBIDDEN = "DELETED_ACCOUNT_TRANSACTION_FORBIDDEN"
    NO_ACCOUNT_BASE_CURRENCY_RATE = "NO_ACCOUNT_BASE_CURRENCY_RATE"
    CURRENCY_MISMATCH = "CURRENCY_MISMATCH"
    ACCOUNT_BALANCE_UNCHANGED = "ACCOUNT_BALANCE_UNCHANGED"
    BASE_CURRENCY_AMOUNT_NOT_ALLOWED = "BASE_CURRENCY_AMOUNT_NOT_ALLOWED"
    BASE_CURRENCY_AMOUNT_REQUIRED = "BASE_CURRENCY_AMOUNT_REQUIRED"
    TRANSFER_AMOUNT_MISMATCH = "TRANSFER_AMOUNT_MISMATCH"
    DESTINATION_AMOUNT_NOT_ALLOWED = "DESTINATION_AMOUNT_NOT_ALLOWED"
    BASE_CURRENCY_NOT_SET = "BASE_CURRENCY_NOT_SET"
    BASE_CURRENCY_ALREADY_SET = "BASE_CURRENCY_ALREADY_SET"
    USERNAME_ALREADY_TAKEN = "USERNAME_ALREADY_TAKEN"
    REDIRECT_URI_NOT_ALLOWED = "REDIRECT_URI_NOT_ALLOWED"
    ORIGIN_NOT_ALLOWED = "ORIGIN_NOT_ALLOWED"
    PROVIDER_UNAVAILABLE = "PROVIDER_UNAVAILABLE"
    PROVIDER_ALREADY_LINKED = "PROVIDER_ALREADY_LINKED"
    IDENTITY_LINKED_TO_ANOTHER_USER = "IDENTITY_LINKED_TO_ANOTHER_USER"
    LAST_IDENTITY_UNLINK_FORBIDDEN = "LAST_IDENTITY_UNLINK_FORBIDDEN"


class ErrorResponse(BaseModel):
    message: str
    error_code: ErrorCodeType | None = None


responses = {
    status.HTTP_418_IM_A_TEAPOT: {
        "description": "Custom errors with possible codes: 400, 401, 403, 404, 409, 501, 502",
        "model": ErrorResponse,
    }
}
